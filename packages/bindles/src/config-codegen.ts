/**
 * Typed ctx.config codegen from a config schema (ADR-0027 / ADR-0037).
 * Agents and runtimes consume generated types; sensitive fields are placeholders.
 */

import type { ConfigFieldDef, ConfigSchema } from "./config-schema.js";
import type { JsonObject } from "./json.js";

function tsTypeForField(field: ConfigFieldDef): string {
	if (field.sensitive) {
		// Sensitive material never materializes as a plain value type in agent/dev.
		// This is emitted TypeScript source: a template-literal *type* in the
		// generated .d.ts. A real template literal would interpolate at codegen
		// time and emit the wrong type.
		return "`[REDACTED:${string}]` | string";
	}
	switch (field.type) {
		case "boolean":
			return "boolean";
		case "int":
			return "number";
		case "json":
			return "unknown";
		case "string":
			if (field.enumValues && field.enumValues.length > 0) {
				return field.enumValues.map((v) => JSON.stringify(v)).join(" | ");
			}
			return "string";
		default:
			return "unknown";
	}
}

/**
 * Generate TypeScript source for a typed `CtxConfig` interface from schema.
 * Suitable for `src/_generated/ctx-config.ts` emission by hobo codegen.
 */
export function generateCtxConfigSource(
	schema: ConfigSchema,
	options?: {
		readonly interfaceName?: string;
		readonly includeSchemaHash?: boolean;
	},
): string {
	const iface = options?.interfaceName ?? "CtxConfig";
	const lines: string[] = [
		"// @generated by @hobo/bindles config codegen (ADR-0027). Do not edit.",
		`// schemaHash: ${schema.schemaHash}`,
		`// schemaVersion: ${schema.schemaVersion}`,
		"",
		`export interface ${iface} {`,
	];
	const entries = Object.entries(schema.fields).sort(([a], [b]) =>
		a < b ? -1 : a > b ? 1 : 0,
	);
	const keys = entries.map(([name]) => name);
	for (const [name, field] of entries) {
		const optional = field.required ? "" : "?";
		const docs = field.docs
			? `  /** ${field.docs.replace(/\*\//g, "*\\/")} */\n`
			: "";
		const sourceNote = `  // source=${field.source} sensitive=${field.sensitive}`;
		lines.push(sourceNote);
		lines.push(
			`${docs}  readonly ${name}${optional}: ${tsTypeForField(field)};`,
		);
	}
	lines.push("}");
	lines.push("");
	lines.push(
		`export type ${iface}Keys = ${
			keys.length === 0
				? "never"
				: keys.map((k) => JSON.stringify(k)).join(" | ")
		};`,
	);
	if (options?.includeSchemaHash !== false) {
		lines.push(
			`export const ${iface}_SCHEMA_HASH = ${JSON.stringify(schema.schemaHash)} as const;`,
		);
	}
	lines.push("");
	return lines.join("\n");
}

/** Agent-safe typed view layout (placeholders only for secrets). */
export type GeneratedAgentConfigView = Readonly<Record<string, string>>;

export function materializeAgentConfigView(
	schema: ConfigSchema,
	values: JsonObject,
): GeneratedAgentConfigView {
	const out: Record<string, string> = {};
	for (const [name, field] of Object.entries(schema.fields)) {
		if (field.sensitive) {
			out[name] = `[REDACTED:${field.source}:${name}]`;
			continue;
		}
		const v = values[name] ?? field.defaultValue;
		if (v === undefined) continue;
		out[name] = String(v);
	}
	return Object.freeze(out);
}
