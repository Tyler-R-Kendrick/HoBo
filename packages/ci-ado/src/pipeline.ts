import { randomUUID } from "node:crypto";
import { readFile, realpath } from "node:fs/promises";
import { isAbsolute, relative, resolve, sep } from "node:path";
import { toJsonString } from "@bufbuild/protobuf";
import {
	executePipeline,
	type ParsedPipeline,
	type PipelineResult,
	PipelineSchema,
	parsePipeline,
} from "@hobo/ci/execution";
import { stringify } from "yaml";
import { createAdoBackend } from "./backend.js";
import {
	type ParsedAdoProject,
	parseAdoProject,
	parseProjectPath,
} from "./project.js";

async function readWithin(workspace: string, path: string): Promise<string> {
	parseProjectPath(path);
	const root = await realpath(workspace);
	const target = await realpath(resolve(root, path));
	const inside = relative(root, target);
	if (inside === ".." || inside.startsWith(`..${sep}`) || isAbsolute(inside))
		throw new Error("configuration path escapes workspace");
	return readFile(target, "utf8");
}

export async function loadAdoProject(workspace: string, configPath: string) {
	const project = parseAdoProject(await readWithin(workspace, configPath));
	const pipeline = parsePipeline(
		await readWithin(workspace, project.pipelinePath),
	);
	pipeline.artifactPaths.forEach(parseProjectPath);
	return Object.freeze({ project, pipeline });
}

/** Every invocation is a new logical run, including a new ADO job attempt. */
export async function runAdoPipeline(
	workspace: string,
	pipeline: ParsedPipeline,
	options: { signal?: AbortSignal } = {},
): Promise<PipelineResult> {
	const execution = parsePipeline(
		toJsonString(PipelineSchema, { ...pipeline, id: randomUUID() }),
	);
	return executePipeline(createAdoBackend({ workspace }), execution, options);
}

/** HoBo monorepo bootstrap; all jobs use an explicitly named self-hosted pool. */
export function renderAzurePipeline(
	project: ParsedAdoProject,
	pipeline: ParsedPipeline,
	configPath: string,
): string {
	parseProjectPath(configPath);
	pipeline.artifactPaths.forEach(parseProjectPath);
	const q = (value: string) => `'${value.replaceAll("'", `'"'"'`)}'`;
	const job = {
		job: "hobo_ci",
		pool: {
			name: project.pool,
			demands: [
				"Agent.OS -equals Linux",
				...project.demands.filter(
					(value) => value !== "Agent.OS -equals Linux",
				),
			],
		},
		timeoutInMinutes: Math.ceil(pipeline.timeoutSeconds / 60) + 10,
		workspace: { clean: "all" },
		steps: [
			{ checkout: "self", clean: true, persistCredentials: false },
			{
				bash: [
					"set -euo pipefail",
					"corepack pnpm install --frozen-lockfile",
					"corepack pnpm exec turbo run build --filter=@hobo/ci-ado --concurrency=100%",
					`node packages/ci-ado/dist/cli.js run ${q(configPath)} .`,
				].join("\n"),
				displayName: "Run HoBo CI checks",
				workingDirectory: "$(Build.SourcesDirectory)",
			},
			...pipeline.artifactPaths.map((path, index) => ({
				task: "PublishPipelineArtifact@1",
				displayName: `Publish ${path}`,
				condition: "succeeded()",
				inputs: {
					targetPath: `$(Build.SourcesDirectory)/${path}`,
					artifact: `${project.artifactPrefix}-${index + 1}`,
					publishLocation: "pipeline",
				},
			})),
		],
	};
	return (
		"# Generated by @hobo/ci-ado. Regenerate after changing the config or artifact list.\n" +
		stringify({ trigger: "none", pr: "none", jobs: [job] }, { lineWidth: 0 })
	);
}
