import type {
	DnsProvider,
	DnsRecord,
	DnsRecordType,
	TenantId,
} from "@hobo/core";

/**
 * DNSControl-oriented provider wrapper.
 *
 * The one-shot does not shell out to DNSControl by default (no hard dependency).
 * Instead it accumulates desired records and can emit a DNSControl-shaped plan
 * that operators apply via their existing DNS-as-Code pipeline.
 */
export function createDnsControlProvider(options?: {
	readonly onPlan?: (plan: DnsControlPlan) => void | Promise<void>;
}): DnsProvider & {
	readonly plans: readonly DnsControlPlan[];
	exportDnsConfigJs(): string;
} {
	const records = new Map<
		string,
		DnsRecord & { zone: string; tenantId: TenantId }
	>();
	const plans: DnsControlPlan[] = [];
	const onPlan = options?.onPlan;

	const api: DnsProvider & {
		readonly plans: readonly DnsControlPlan[];
		exportDnsConfigJs(): string;
	} = {
		kind: "dnscontrol",
		get plans() {
			return plans;
		},
		async upsert(tenantId, zone, record) {
			const k = `${tenantId}::${zone}::${record.name}::${record.type}`;
			records.set(k, { ...record, zone, tenantId });
			const plan: DnsControlPlan = {
				action: "upsert",
				tenantId,
				zone,
				record,
				at: new Date().toISOString(),
			};
			plans.push(plan);
			await onPlan?.(plan);
		},
		async remove(tenantId, zone, name, type: DnsRecordType) {
			const k = `${tenantId}::${zone}::${name}::${type}`;
			records.delete(k);
			const plan: DnsControlPlan = {
				action: "remove",
				tenantId,
				zone,
				record: {
					name,
					type,
					content: "",
					gatewayTarget: true,
				},
				at: new Date().toISOString(),
			};
			plans.push(plan);
			await onPlan?.(plan);
		},
		async list(tenantId, zone) {
			return [...records.values()]
				.filter((r) => r.tenantId === tenantId && r.zone === zone)
				.map(({ name, type, content, ttl, gatewayTarget }) => ({
					name,
					type,
					content,
					...(ttl !== undefined ? { ttl } : undefined),
					gatewayTarget,
				}));
		},
		exportDnsConfigJs() {
			const byZone = new Map<string, DnsRecord[]>();
			for (const rec of records.values()) {
				const list = byZone.get(rec.zone) ?? [];
				list.push(rec);
				byZone.set(rec.zone, list);
			}
			const lines = [
				"// Generated by @hobo/connectivity createDnsControlProvider — apply with DNSControl",
				"// Public records must target authenticated gateways only.",
			];
			for (const [zone, list] of byZone) {
				lines.push(`D("${zone}", REG_CHANGEME,`);
				for (const r of list) {
					const ttl = r.ttl ?? 300;
					if (r.type === "CNAME") {
						lines.push(`  CNAME("${r.name}", "${r.content}.", TTL(${ttl})),`);
					} else if (r.type === "A") {
						lines.push(`  A("${r.name}", "${r.content}", TTL(${ttl})),`);
					} else if (r.type === "AAAA") {
						lines.push(`  AAAA("${r.name}", "${r.content}", TTL(${ttl})),`);
					} else {
						lines.push(`  TXT("${r.name}", "${r.content}", TTL(${ttl})),`);
					}
				}
				lines.push(");");
			}
			return `${lines.join("\n")}\n`;
		},
	};
	return api;
}

export interface DnsControlPlan {
	readonly action: "upsert" | "remove";
	readonly tenantId: TenantId;
	readonly zone: string;
	readonly record: DnsRecord;
	readonly at: string;
}
