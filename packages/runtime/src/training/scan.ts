import type {
	DeclaredOperation,
	DeclaredParameter,
	DeclaredTrainableClass,
} from "ts-autocode-grounding";
import {
	generateDeclaredRegistrations as emitRegistrations,
	scanDeclaredTrainables as scanWithGrounding,
} from "ts-autocode-grounding";

// Source scanner for ambient trainable declarations (Plan 2 Syntax 0,
// `hobo stub` path). An `export declare class` is erased at compile time —
// no decorator ever runs — so the syntax below is honored statically:
//
//   @trainable
//   export declare class Program {
//     @intent("Produce a simple hello-world program")
//     @returns("Hello World! or Hello, <name>! when supplied")
//     trainableMethod(
//       @description("Optional person to greet")
//       name?: string,
//     ): string;
//   }
//
// Every decorator is optional: a bare `@trainable declare class` with
// undecorated method signatures still scans — intent is inferred and the
// TypeScript signature is the declared shape. Scanning and emission are
// delegated to ts-autocode-grounding (ADR-0128): a real TypeScript AST
// walk, replacing the previous regex + bracket-counting parser.

export type { DeclaredOperation, DeclaredParameter, DeclaredTrainableClass };

/** Scan source for `@trainable` classes (ambient or not) and their declared operations. */
export function scanDeclaredTrainables(
	source: string,
): readonly DeclaredTrainableClass[] {
	return scanWithGrounding(source);
}

/**
 * Generate the registration source for a scanned class: one
 * `export const <method> = defineGrounding({...})` per operation, importing
 * `defineGrounding` from `@hobo/runtime` (granular.ts; it is `training.define`).
 * `hobo stub` writes these registrations for every ambient
 * `@trainable declare class` under the project's source dir, one module per
 * class at `src/_generated/declared/<Class>.ts`, re-exported from
 * `trainables.ts`. Given the class's source `file`, this returns that module
 * byte for byte, header included, when the codegen layout's runtime module is
 * the default `@hobo/runtime` (packages/cli/test/declared-trainable-codegen.test.ts
 * holds the two to it). The declared TypeScript signature becomes the
 * contract's shape descriptors, so the registration grounds (shape present)
 * even with every decorator omitted.
 */
export function generateDeclaredRegistrations(
	declared: DeclaredTrainableClass,
	source: { readonly file?: string } = {},
): string {
	return emitRegistrations(declared, {
		runtimeModule: "@hobo/runtime",
		header: [
			"// Generated by hobo codegen — do not edit.",
			`// Registrations for the ambient @trainable class ${declared.className}${source.file === undefined ? "" : ` in ${source.file}`}`,
			"// (Plan 2 Syntax 0, ADR-0128): signature-only, served by the stub baseline.",
		],
	});
}
