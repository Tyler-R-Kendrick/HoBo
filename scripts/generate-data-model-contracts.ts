import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const PROTO_PATH = "contracts/data-models/data-models.proto";
const CUE_PATH = "contracts/data-models/data-models.cue";
const README_PATH = "contracts/data-models/README.md";

const args = new Set(process.argv.slice(2));
const check = args.has("--check");

const sourceFiles = execFileSync("git", ["ls-files", "src/draft"], {
  encoding: "utf8",
})
  .split("\n")
  .filter(Boolean)
  .filter((file) => /^src\/draft\/[^/]+\/src\/.+\.ts$/u.test(file))
  .filter((file) => !file.endsWith(".d.ts") && !file.endsWith(".d.mts"))
  .filter((file) => !file.includes("/generated/"));

const dataModels = sourceFiles.map((path) => {
  const parts = path.split("/");
  const packageName = parts[2] ?? "draft";
  const basename = parts.at(-1)?.replace(/\.ts$/, "") ?? packageName;
  const domain = packageName.replace(/-(contract|poc|spike|suite)$/u, "");
  const protoMessage = `${toPascalCase(packageName)}${toPascalCase(basename)}DataModel`;
  const contractId = `hobo.datamodel.${packageName}.${basename}`;
  return { path, packageName, basename, domain, protoMessage, contractId };
});

const duplicateMessages = findDuplicates(dataModels.map((model) => model.protoMessage));
if (duplicateMessages.length > 0) {
  throw new Error(`duplicate protobuf model messages: ${duplicateMessages.join(", ")}`);
}

const proto = renderProto(dataModels);
const cue = renderCue(dataModels);
const readme = renderReadme(dataModels.length);

if (check) {
  assertSame(PROTO_PATH, proto);
  assertSame(CUE_PATH, cue);
  assertSame(README_PATH, readme);
  console.log(`data model contracts ok (${dataModels.length} models)`);
} else {
  mkdirSync(dirname(PROTO_PATH), { recursive: true });
  writeFileSync(PROTO_PATH, proto);
  writeFileSync(CUE_PATH, cue);
  writeFileSync(README_PATH, readme);
  console.log(`wrote data model contracts (${dataModels.length} models)`);
}

function renderProto(models: typeof dataModels): string {
  const messages = models
    .map((model) => `message ${model.protoMessage} {\n  option (hobo.data_model_contract_id) = "${model.contractId}";\n  option (hobo.source_path) = "${model.path}";\n  option (hobo.cue_annotation) = "contracts/data-models/data-models.cue#${model.protoMessage}";\n\n  string contract_id = 1;\n  string source_path = 2;\n  string package_name = 3;\n  string domain = 4;\n  repeated string integration_boundaries = 5;\n  bool cue_annotated = 6;\n}\n`)
    .join("\n");

  return `syntax = "proto3";\n\npackage hobo.datamodels.v1;\n\nimport "google/protobuf/descriptor.proto";\n\nextend google.protobuf.MessageOptions {\n  string data_model_contract_id = 50001;\n  string source_path = 50002;\n  string cue_annotation = 50003;\n}\n\nmessage DataModelCatalog {\n  repeated DataModelCatalogEntry entries = 1;\n}\n\nmessage DataModelCatalogEntry {\n  string contract_id = 1;\n  string protobuf_message = 2;\n  string cue_definition = 3;\n  string source_path = 4;\n  string package_name = 5;\n  string domain = 6;\n}\n\n${messages}`;
}

function renderCue(models: typeof dataModels): string {
  const entries = models
    .map((model) => `\t{\n\t\tcontractId:       "${model.contractId}"\n\t\tprotobufMessage:  "${model.protoMessage}"\n\t\tprotobufPackage:  "hobo.datamodels.v1"\n\t\tcueDefinition:    "#${model.protoMessage}"\n\t\tsourcePath:       "${model.path}"\n\t\tpackageName:      "${model.packageName}"\n\t\tdomain:           "${model.domain}"\n\t\tintegrationBoundaries: ["module", "contract", "test"]\n\t\tcueAnnotated:     true\n\t},`)
    .join("\n");

  const definitions = models
    .map((model) => `#${model.protoMessage}: #DataModel & {\n\tcontractId:      "${model.contractId}"\n\tprotobufMessage: "${model.protoMessage}"\n\tsourcePath:      "${model.path}"\n\tpackageName:     "${model.packageName}"\n\tdomain:          "${model.domain}"\n}\n`)
    .join("\n");

  return `package datamodels\n\n#DataModel: {\n\tcontractId:       =~"^hobo\\\\.datamodel\\\\.[a-z0-9-]+\\\\.[a-z0-9-]+$"\n\tprotobufMessage:  =~"^[A-Z][A-Za-z0-9]+DataModel$"\n\tprotobufPackage:  "hobo.datamodels.v1"\n\tcueDefinition:    =~"^#[A-Z][A-Za-z0-9]+DataModel$"\n\tsourcePath:       =~"^src/draft/.+/src/.+\\\\.ts$"\n\tpackageName:      =~"^[a-z0-9][a-z0-9-]+$"\n\tdomain:           =~"^[a-z0-9][a-z0-9-]+$"\n\tintegrationBoundaries: [..."module" | "contract" | "test" | "provider" | "event" | "persistence" | "cli" | "api"]\n\tcueAnnotated:     true\n}\n\n#Catalog: {\n\tentries: [...#DataModel]\n\tentries: [${models.map((model) => `#${model.protoMessage}`).join(", ")}]\n}\n\ncatalog: #Catalog & {\n\tentries: [\n${entries}\n\t]\n}\n\n${definitions}`;
}

function renderReadme(count: number): string {
  return `# Data model contracts\n\nThis directory is generated by \`node --import tsx scripts/generate-data-model-contracts.ts\`. It is the repository-wide bridge that makes every HoBo-authored TypeScript data-model module visible to Protobuf and CUE.\n\n- \`data-models.proto\` declares one protobuf message per tracked data-model source module and annotates each message with its source path plus CUE definition.\n- \`data-models.cue\` constrains every protobuf-backed data model with source-path, package, domain, integration-boundary, and \`cueAnnotated: true\` invariants.\n- \`npm run contracts:data-models\` verifies the generated Protobuf/CUE catalog stays in sync with tracked TypeScript data-model modules.\n\nCurrent generated coverage: ${count} TypeScript data-model modules.\n`;
}

function assertSame(path: string, expected: string): void {
  const actual = readFileSync(path, "utf8");
  if (actual !== expected) {
    throw new Error(`${path} is stale; run node --import tsx scripts/generate-data-model-contracts.ts`);
  }
}

function toPascalCase(value: string): string {
  return value
    .replace(/[^a-zA-Z0-9]+/gu, " ")
    .split(" ")
    .filter(Boolean)
    .map((part) => `${part[0]?.toUpperCase() ?? ""}${part.slice(1)}`)
    .join("");
}

function findDuplicates(values: string[]): string[] {
  const seen = new Set<string>();
  const duplicates = new Set<string>();
  for (const value of values) {
    if (seen.has(value)) duplicates.add(value);
    seen.add(value);
  }
  return [...duplicates].sort();
}
