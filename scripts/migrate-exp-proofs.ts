/**
 * One-off migration: reorganize `src/draft/exp-proofs/<slug>` into experience-type
 * subfolders `src/draft/exp-proofs/<type>/<slug>` per `src/draft/exp-proofs/_classification.md`.
 *
 * Kept in-repo for audit. Safe to run only on a clean, pre-migration working tree:
 * it `git mv`s each package, rewrites every tracked textual reference (absolute-style
 * `exp-proofs/<slug>` paths get the type inserted; relative `../` chains inside moved
 * packages that climb out of the package gain one level), and patches the path-shape
 * assumptions in workspace/checker configuration.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const repoRoot = path.resolve(import.meta.dirname, "..");
const expRoot = path.join(repoRoot, "src/draft/exp-proofs");
const TYPES = ["dx", "ux", "cx", "ax", "api"] as const;
type ExperienceType = (typeof TYPES)[number];

function git(...args: string[]) {
  return execFileSync("git", args, { cwd: repoRoot, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
}

function parseClassification(): Map<string, ExperienceType> {
  const manifest = readFileSync(path.join(expRoot, "_classification.md"), "utf8");
  const map = new Map<string, ExperienceType>();
  let current: ExperienceType | undefined;
  for (const line of manifest.split("\n")) {
    const heading = line.match(/^## (dx|ux|cx|ax|api) \(\d+\)/u);
    if (heading) {
      current = heading[1] as ExperienceType;
      continue;
    }
    const row = line.match(/^\| `([a-z0-9-]+)` \|/u);
    if (row && current) map.set(row[1]!, current);
  }
  if (map.size === 0) throw new Error("classification manifest parsed to zero rows");
  return map;
}

const TEXT_EXTENSIONS = new Set([
  ".ts", ".mts", ".cts", ".mjs", ".cjs", ".js", ".json", ".md", ".mdc", ".cue", ".proto",
  ".yaml", ".yml", ".feature", ".wit", ".txt", ".toml", ".d.ts",
]);

function isTextFile(file: string) {
  if (file === "pnpm-lock.yaml") return false; // regenerated by pnpm install
  return TEXT_EXTENSIONS.has(path.extname(file)) || file.endsWith(".d.ts");
}

function main() {
  const slugToType = parseClassification();
  console.log(`classification: ${slugToType.size} packages`);

  // 1. git mv each package into its type folder.
  for (const type of TYPES) mkdirSync(path.join(expRoot, type), { recursive: true });
  let moved = 0;
  for (const [slug, type] of slugToType) {
    const from = path.join(expRoot, slug);
    const to = path.join(expRoot, type, slug);
    if (!existsSync(from)) {
      if (existsSync(to)) continue; // already migrated
      throw new Error(`package missing at both old and new location: ${slug}`);
    }
    if (existsSync(to)) {
      // A pre-existing target (e.g. stale untracked node_modules from an earlier run) would make
      // `git mv` nest the source INSIDE the target. Refuse and let the operator clean up first.
      throw new Error(`target already exists (stale leftovers?): ${path.relative(repoRoot, to)}`);
    }
    git("mv", path.relative(repoRoot, from), path.relative(repoRoot, to));
    moved += 1;
  }
  console.log(`git mv complete: ${moved} packages`);

  // 2. Global pass — insert the type into every `exp-proofs/<slug>` textual reference.
  const slugAlternation = [...slugToType.keys()]
    .sort((a, b) => b.length - a.length)
    .map((s) => s.replaceAll(/[.*+?^${}()|[\]\\]/gu, "\\$&"))
    .join("|");
  const slugRef = new RegExp(`exp-proofs/(${slugAlternation})(?![a-z0-9-])`, "gu");
  const tracked = git("ls-files").split("\n").filter(Boolean).filter(isTextFile);
  let rewrittenFiles = 0;
  for (const file of tracked) {
    const abs = path.join(repoRoot, file);
    const before = readFileSync(abs, "utf8");
    const after = before.replaceAll(slugRef, (_m, slug: string) => `exp-proofs/${slugToType.get(slug)}/${slug}`);
    if (after !== before) {
      writeFileSync(abs, after);
      rewrittenFiles += 1;
    }
  }
  console.log(`type-insert pass: ${rewrittenFiles} files rewritten`);

  // 3. Depth pass — inside moved packages, `../` chains that climb out of the package gain one level.
  //    A file at package-relative directory depth d exits the package once it climbs d+1 levels
  //    (pre-move that landed in exp-proofs/ or above; post-move those targets are one level further).
  const upRun = /(?:\.\.\/)+/gu;
  let depthPatched = 0;
  for (const file of git("ls-files").split("\n").filter(Boolean).filter(isTextFile)) {
    const match = file.match(/^src\/draft\/exp-proofs\/(?:dx|ux|cx|ax|api)\/[^/]+\/(.*)$/u);
    if (!match) continue;
    const depth = match[1]!.split("/").length - 1; // directories between package root and the file
    const abs = path.join(repoRoot, file);
    const before = readFileSync(abs, "utf8");
    const after = before.replaceAll(upRun, (run, offset: number, whole: string) => {
      if (whole[offset + run.length] === ".") return run; // don't split a trailing `..`
      const ups = run.length / 3;
      return ups >= depth + 1 ? "../".repeat(ups + 1) : run;
    });
    if (after !== before) {
      writeFileSync(abs, after);
      depthPatched += 1;
    }
  }
  console.log(`depth pass: ${depthPatched} files patched`);

  // 3b. Bare-sibling pass — relative refs inside moved packages whose first segment after the
  //     `../` chain is itself an exp-proof slug (`../../<sibling>/…`) need the sibling's type
  //     inserted (the global pass only matches `exp-proofs/<slug>` forms).
  const bareSibling = new RegExp(`((?:\\.\\./)+)(${slugAlternation})(?![a-z0-9-])`, "gu");
  let siblingPatched = 0;
  for (const file of git("ls-files", "src/draft/exp-proofs").split("\n").filter(Boolean).filter(isTextFile)) {
    const abs = path.join(repoRoot, file);
    const before = readFileSync(abs, "utf8");
    const after = before.replaceAll(bareSibling, (_m, ups: string, slug: string) => `${ups}${slugToType.get(slug)}/${slug}`);
    if (after !== before) {
      writeFileSync(abs, after);
      siblingPatched += 1;
    }
  }
  console.log(`bare-sibling pass: ${siblingPatched} files patched`);

  // 4. Path-shape infrastructure patches (each asserts its target string exists exactly once).
  const patches: Array<{ file: string; from: string; to: string; count?: number }> = [
    {
      file: "pnpm-workspace.yaml",
      from: '  - "src/draft/exp-proofs/*"',
      to: '  - "src/draft/exp-proofs/*/*"',
    },
    {
      file: "scripts/relevant-check-policy.ts",
      from: `  const draft = normalized.match(/^src\\/draft\\/(technical-proofs|exp-proofs|epic-proofs|projects)\\/([^/]+)\\//u);
  if (draft) return \`src/draft/\${draft[1]}/\${draft[2]}\`;`,
      to: `  const draft = normalized.match(/^src\\/draft\\/(technical-proofs|epic-proofs|projects)\\/([^/]+)\\//u);
  if (draft) return \`src/draft/\${draft[1]}/\${draft[2]}\`;
  const exp = normalized.match(/^src\\/draft\\/exp-proofs\\/(dx|ux|cx|ax|api)\\/([^/]+)\\//u);
  if (exp) return \`src/draft/exp-proofs/\${exp[1]}/\${exp[2]}\`;`,
    },
    {
      file: "scripts/check-architecture-guardrails.mjs",
      from: `  if (DRAFT_PROOF_KINDS.has(parts[2]) && parts[3]) {
    return parts.slice(0, 4).join("/");
  }

  return parts[2] && parts[2] !== "README.md" && parts[2] !== "AGENTS.md"
    ? parts.slice(0, 3).join("/")
    : undefined;`,
      to: `  // Aggregate metadata (underscore-prefixed like _templates/_registry.md) and loose files
  // directly under src/draft/<kind>/ are never proof packages.
  const isPackageDir = (segment, next) => segment && !segment.startsWith("_") && next !== undefined;

  if (parts[2] === "exp-proofs" && parts[3] && !parts[3].startsWith("_")) {
    return isPackageDir(parts[4], parts[5]) ? parts.slice(0, 5).join("/") : undefined;
  }

  if (DRAFT_PROOF_KINDS.has(parts[2])) {
    return isPackageDir(parts[3], parts[4]) ? parts.slice(0, 4).join("/") : undefined;
  }

  return undefined;`,
    },
    {
      file: "src/draft/epic-proofs/v1-vibe-example-gap-closure/architecture/vibe_example_gap_closure.cue",
      from: 'target_package_path: =~"^src/draft/exp-proofs/[a-z0-9-]+$"',
      to: 'target_package_path: =~"^src/draft/exp-proofs/(dx|ux|cx|ax|api)/[a-z0-9-]+$"',
      count: 2,
    },
    {
      file: "src/draft/epic-proofs/v1-vibe-example-gap-closure/src/vibe-gap-closure.ts",
      from: "    targetPackagePath: `src/draft/exp-proofs/${packageSlug}`,\n    proofNotePath: `docs/design/proofs/${issueSlug}/README.md`,",
      to: "    targetPackagePath: `src/draft/exp-proofs/ux/${packageSlug}`,\n    proofNotePath: `docs/design/proofs/${issueSlug}/README.md`,",
    },
    {
      file: "src/draft/epic-proofs/v1-vibe-example-gap-closure/src/vibe-gap-closure.ts",
      from: "    targetPackagePath: `src/draft/exp-proofs/${packageSlug}`,\n    proofNotePath: `docs/design/proofs/${packageSlug}/README.md`,",
      to: "    targetPackagePath: `src/draft/exp-proofs/dx/${packageSlug}`,\n    proofNotePath: `docs/design/proofs/${packageSlug}/README.md`,",
    },
    {
      file: "src/draft/epic-proofs/v1-vibe-example-gap-closure/src/vibe-gap-closure.ts",
      from: "must target src/draft/exp-proofs/<slug>",
      to: "must target src/draft/exp-proofs/<type>/<slug>",
      count: 2,
    },
    {
      file: "src/draft/epic-proofs/v1-vibe-example-gap-closure/tests/vibe-gap-closure.test.ts",
      from: "assert.match(issue.targetPackagePath, /^src\\/draft\\/exp-proofs\\/[a-z0-9-]+$/);",
      to: "assert.match(issue.targetPackagePath, /^src\\/draft\\/exp-proofs\\/(dx|ux|cx|ax|api)\\/[a-z0-9-]+$/);",
    },
  ];
  for (const patch of patches) {
    const abs = path.join(repoRoot, patch.file);
    const before = readFileSync(abs, "utf8");
    const expected = patch.count ?? 1;
    const occurrences = before.split(patch.from).length - 1;
    if (occurrences !== expected) {
      throw new Error(`${patch.file}: expected ${expected} occurrence(s) of patch target, found ${occurrences}`);
    }
    writeFileSync(abs, before.replaceAll(patch.from, patch.to));
    console.log(`patched: ${patch.file}`);
  }

  // 5. run-tests.ts — add three-level exp-proof globs alongside the two-level draft globs.
  const runTests = path.join(repoRoot, "scripts/run-tests.ts");
  let runTestsSource = readFileSync(runTests, "utf8");
  const globAdditions: Array<[string, string]> = [
    ['"src/draft/*/*/test/*test.ts"', '"src/draft/*/*/test/*test.ts", "src/draft/exp-proofs/*/*/test/*test.ts"'],
    ['"src/draft/*/*/test/*test.mjs"', '"src/draft/*/*/test/*test.mjs", "src/draft/exp-proofs/*/*/test/*test.mjs"'],
    ['"src/draft/*/*/tests/*test.ts"', '"src/draft/*/*/tests/*test.ts", "src/draft/exp-proofs/*/*/tests/*test.ts"'],
    ['"src/draft/*/*/tests/*test.mjs"', '"src/draft/*/*/tests/*test.mjs", "src/draft/exp-proofs/*/*/tests/*test.mjs"'],
    ['"src/draft/*/*/type-tests/*.ts"', '"src/draft/*/*/type-tests/*.ts", "src/draft/exp-proofs/*/*/type-tests/*.ts"'],
    ['"src/draft/*/*/test-types/*.ts"', '"src/draft/*/*/test-types/*.ts", "src/draft/exp-proofs/*/*/test-types/*.ts"'],
    ['"src/draft/*/*/test/*contract*.test.ts"', '"src/draft/*/*/test/*contract*.test.ts", "src/draft/exp-proofs/*/*/test/*contract*.test.ts"'],
    ['"src/draft/*/*/test/*contract*.test.mjs"', '"src/draft/*/*/test/*contract*.test.mjs", "src/draft/exp-proofs/*/*/test/*contract*.test.mjs"'],
    ['"src/draft/*/*/tests/*contract*.test.ts"', '"src/draft/*/*/tests/*contract*.test.ts", "src/draft/exp-proofs/*/*/tests/*contract*.test.ts"'],
    ['"src/draft/*/*/tests/*contract*.test.mjs"', '"src/draft/*/*/tests/*contract*.test.mjs", "src/draft/exp-proofs/*/*/tests/*contract*.test.mjs"'],
    ['"src/draft/*/*/contracts/consumer/*test.ts"', '"src/draft/*/*/contracts/consumer/*test.ts", "src/draft/exp-proofs/*/*/contracts/consumer/*test.ts"'],
    ['"src/draft/*/*/test/*provider*.test.ts"', '"src/draft/*/*/test/*provider*.test.ts", "src/draft/exp-proofs/*/*/test/*provider*.test.ts"'],
    ['"src/draft/*/*/test/*provider*.test.mjs"', '"src/draft/*/*/test/*provider*.test.mjs", "src/draft/exp-proofs/*/*/test/*provider*.test.mjs"'],
    ['"src/draft/*/*/tests/*provider*.test.ts"', '"src/draft/*/*/tests/*provider*.test.ts", "src/draft/exp-proofs/*/*/tests/*provider*.test.ts"'],
    ['"src/draft/*/*/tests/*provider*.test.mjs"', '"src/draft/*/*/tests/*provider*.test.mjs", "src/draft/exp-proofs/*/*/tests/*provider*.test.mjs"'],
  ];
  for (const [from, to] of globAdditions) {
    if (!runTestsSource.includes(from)) throw new Error(`run-tests.ts: glob target not found: ${from}`);
    runTestsSource = runTestsSource.replace(from, to);
  }
  writeFileSync(runTests, runTestsSource);
  console.log("patched: scripts/run-tests.ts globs");

  console.log("migration complete — now run: pnpm install && pnpm agent:check");
}

main();
