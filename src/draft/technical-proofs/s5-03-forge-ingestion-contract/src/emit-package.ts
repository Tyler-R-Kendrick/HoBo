import { mkdir, mkdtemp, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

import type { ParsedIngestion } from "./parse-sources.js";
import { ForgeIngestionError, sha256Digest, type DigestRef } from "./events.js";



const packageRoot = fileURLToPath(new URL("..", import.meta.url));

export type CandidatePackageFile = {
  relativePath: string;
  bytes: string;
};

export type EmittedCandidatePackage = {
  providerId: string;
  rootDir: string;
  files: CandidatePackageFile[];
  packageRef: DigestRef;
};

export function buildCandidatePackageFiles(parsed: ParsedIngestion): CandidatePackageFile[] {
  const manifestDraft = JSON.stringify(
    {
      schema: "hobo.capability-manifest.draft/v1",
      providerId: parsed.providerId,
      targetWitPort: parsed.targetWitPort,
      claims: parsed.capabilityManifest.claims ?? [],
      networkEgress: parsed.capabilityManifest.networkEgress ?? false,
      equivalenceClasses: parsed.equivalenceClasses
    },
    null,
    2
  );

  const witBindings = normalizeSource(`
// WIT binding skeleton generated by forge ingestion.
export const targetWitPort = ${JSON.stringify(parsed.targetWitPort)};

export interface DatabaseProvider {
  connect(): Promise<void>;
  query(sql: string): Promise<unknown>;
  destroy(): Promise<void>;
}

export function bindDatabaseProvider(impl: DatabaseProvider): DatabaseProvider {
  return impl;
}
`);

  const equivalenceMapping = normalizeSource(`
// Equivalence-class mapping skeleton generated from capability manifest + terraform hints.
export const equivalenceClasses = ${JSON.stringify(parsed.equivalenceClasses, null, 2)} as const;

export const terraformHints = ${JSON.stringify(parsed.terraformComments, null, 2)} as const;

export function mapResourceClass(port: string): string | undefined {
  const match = equivalenceClasses.find((entry) => entry.port === port);
  return typeof match?.resourceClass === "string" ? match.resourceClass : undefined;
}
`);

  const providerIndex = normalizeSource(`
import { bindDatabaseProvider, type DatabaseProvider } from "./wit-bindings.js";
import { mapResourceClass } from "./equivalence-mapping.js";

export const providerId = ${JSON.stringify(parsed.providerId)};
export const targetWitPort = ${JSON.stringify(parsed.targetWitPort)};
export const conformanceSuiteId = ${JSON.stringify(parsed.conformanceSuiteId)};

export function createProvider(): DatabaseProvider {
  const mappedClass = mapResourceClass("database");
  if (!mappedClass) {
    throw new Error("equivalence-mapping-missing:database");
  }

  return bindDatabaseProvider({
    async connect() {
      // <hobo-fill>
      throw new Error("scaffold-placeholder:connect");
      // </hobo-fill>
    },
    async query(_sql: string) {
      // <hobo-fill>
      throw new Error("scaffold-placeholder:query");
      // </hobo-fill>
    },
    async destroy() {
      // <hobo-fill>
      throw new Error("scaffold-placeholder:destroy");
      // </hobo-fill>
    }
  });
}
`);

  const packageJson = JSON.stringify(
    {
      name: parsed.providerId.replace("@", ""),
      version: "0.0.0-candidate",
      private: true,
      type: "module",
      exports: {
        ".": "./src/index.ts"
      }
    },
    null,
    2
  );

  const tsconfig = JSON.stringify(
    {
      compilerOptions: {
        target: "ES2022",
        module: "NodeNext",
        moduleResolution: "NodeNext",
        strict: true,
        noEmit: true,
        skipLibCheck: true
      },
      include: ["src/**/*.ts"]
    },
    null,
    2
  );

  return [
    { relativePath: "package.json", bytes: packageJson },
    { relativePath: "tsconfig.json", bytes: tsconfig },
    { relativePath: "capability-manifest.draft.json", bytes: manifestDraft },
    { relativePath: "src/wit-bindings.ts", bytes: witBindings },
    { relativePath: "src/equivalence-mapping.ts", bytes: equivalenceMapping },
    { relativePath: "src/index.ts", bytes: providerIndex }
  ];
}

export async function emitCandidatePackage(
  parsed: ParsedIngestion,
  options: { outputDir?: string } = {}
): Promise<EmittedCandidatePackage> {
  const files = buildCandidatePackageFiles(parsed);
  const rootDir =
    options.outputDir ?? (await mkdtemp(path.join(os.tmpdir(), "hobo-forge-candidate-")));

  await mkdir(path.join(rootDir, "src"), { recursive: true });

  for (const file of files) {
    const target = path.join(rootDir, file.relativePath);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, file.bytes, "utf8");
  }

  const packageRef = {
    uri: `draft://forge-candidate/${parsed.requestId}@${sha256Digest(files)}`,
    digest: sha256Digest(files)
  };

  return {
    providerId: parsed.providerId,
    rootDir,
    files,
    packageRef
  };
}

export function compileCandidatePackage(rootDir: string): { ok: true } | { ok: false; stderr: string } {
  const workspaceRoot = path.resolve(packageRoot, "../../../..");
  const typescriptEntry = path.join(workspaceRoot, "node_modules", "typescript", "bin", "tsc");
  const result = spawnSync(process.execPath, [typescriptEntry, "--project", path.join(rootDir, "tsconfig.json"), "--noEmit"], {
    encoding: "utf8",
    env: process.env,
    stdio: ["ignore", "pipe", "pipe"]
  });

  if (result.status === 0) {
    return { ok: true };
  }

  return {
    ok: false,
    stderr: `${result.stdout ?? ""}${result.stderr ?? ""}`.trim()
  };
}

export function assertCandidateCompiles(rootDir: string): void {
  const result = compileCandidatePackage(rootDir);
  if (!result.ok) {
    throw new ForgeIngestionError("forge.package.compile_failed", result.stderr);
  }
}

function normalizeSource(source: string): string {
  return source.trimStart().replace(/\r\n/g, "\n").trimEnd() + "\n";
}
